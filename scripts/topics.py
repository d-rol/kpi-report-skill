"""Тема обращения из штатного классификатора Омнидеска.

Что это. У обращения есть кастомное поле-справочник «Тема обращения», привязанное
к группе (по одному полю на продукт). Значение проставляет автоматика по первым
сообщениям клиента, поэтому разметка появляется сама и её не нужно выводить из
текста заново.

Почему отдельный модуль, а не три строчки в отчёте. Здесь ровно одна нетривиальная
вещь — **охват**. Тема проставляется не у всех обращений: классификатор включили
позже, чем начали работать, и на части периода темы нет вовсе. Если считать доли
от всего потока, «возвраты — 3%» будет означать не «возвратов мало», а «размечено
мало», и это одинаково выглядит. Поэтому:

  * доли считаются от РАЗМЕЧЕННЫХ обращений, а не от всего потока;
  * охват (сколько размечено из скольких) возвращается рядом с числами и печатается
    всегда, даже когда он нулевой;
  * при низком охвате поднимается флаг `low_coverage` — потребитель обязан сказать
    об этом вслух, а не молча показать красивый топ.

Это тот же принцип, что в `load_baseline`: «сравнивать не с чем» и «всё как обычно»
— разные утверждения, и путать их нельзя, когда от отчёта зависят деньги.
"""
import re
import collections

# Поле называется по-разному для разных продуктов («Тема обращения (продукт А)»,
# «Тема обращения (продукт Б)»), но роль у них одна. Ищем по названию, а не по
# id: id у каждой установки свои, а название задаёт тот, кто настраивал поле.
TOPIC_RE = re.compile(r"тема обращения", re.I)

# Ниже этой доли размеченных разрез по темам показывать можно, но только с
# оговоркой: на таком охвате порядок тем ещё может перевернуться.
MIN_COVERAGE = 0.8


def topic_fields(client):
    """Поля-классификаторы: {field_id: описание}. Один запрос к API.

    Берём только поля УРОВНЯ ОБРАЩЕНИЯ: одноимённое поле уровня клиента
    описывало бы человека, а не обращение, и разрез по нему означал бы другое.
    """
    out = {}
    for fid, f in (client.custom_fields_map() or {}).items():
        if f.get("field_level") != "case":
            continue
        if TOPIC_RE.search(f.get("title") or ""):
            out[str(fid)] = f
    return out


def case_topic(case, fields):
    """Название темы обращения или None, если тема не проставлена.

    Именно None, а не пустая строка: «темы нет» и «тема пустая» в разборе
    должны быть одним и тем же, и это одно значение не должно попадать в топ.
    """
    for key, raw in (case.get("custom_fields") or {}).items():
        fid = key[3:] if key.startswith("cf_") else key
        f = fields.get(str(fid))
        if not f or raw in (None, "", []):
            continue
        data = f.get("field_data") or {}
        # В обращении лежит ключ варианта. Если ключа нет в справочнике (вариант
        # удалили из списка после того, как его проставили) — отдаём сырое
        # значение: потерять обращение хуже, чем показать непонятный код.
        return data.get(str(raw), str(raw))
    return None


def summary(rows):
    """Сводка по темам. `rows` — список (тема или None, нарушение ли это).

    Возвращает охват и таблицу «тема -> сколько всего, сколько просрочек, доля».
    Доля просрочек считается внутри темы (просрочки / обращения этой темы) —
    она отвечает на вопрос «какие темы даются тяжелее», и в отличие от доли от
    всего потока не зависит от того, насколько полно размечен период.
    """
    total = len(rows)
    tagged = [(t, v) for t, v in rows if t]
    per = collections.defaultdict(lambda: {"cases": 0, "violations": 0})
    for topic, is_viol in tagged:
        per[topic]["cases"] += 1
        if is_viol:
            per[topic]["violations"] += 1
    items = []
    for topic, v in per.items():
        items.append({
            "topic": topic,
            "cases": v["cases"],
            "violations": v["violations"],
            "violation_rate": round(v["violations"] / v["cases"], 3) if v["cases"] else None,
        })
    # Сортируем по числу просрочек: отчёт отвечает на вопрос «где болит», а не
    # «чего больше всего». При равенстве — по объёму, чтобы порядок был устойчив.
    items.sort(key=lambda x: (-x["violations"], -x["cases"], x["topic"]))
    coverage = round(len(tagged) / total, 3) if total else 0.0
    return {
        "cases_total": total,
        "cases_tagged": len(tagged),
        "coverage": coverage,
        "low_coverage": coverage < MIN_COVERAGE,
        "untagged_violations": sum(1 for t, v in rows if not t and v),
        "topics": items,
    }
